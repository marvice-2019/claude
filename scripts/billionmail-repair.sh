#!/usr/bin/env bash
# Repairs the 502 on email.marvice.tech for BillionMail behind Coolify's Traefik.
#
#   curl -fsSL https://raw.githubusercontent.com/marvice-2019/claude/main/scripts/billionmail-repair.sh | bash
#
# Instead of attaching the panel container to Traefik's network (Docker labels),
# this publishes the panel on the host and adds a Coolify dynamic route:
#   Traefik -> http://host.docker.internal:<HTTP_PORT>
# The Hostinger firewall keeps that port closed to the internet.
# Ends with one line: RESULT: PASS ... or RESULT: FAIL ... (that's all you need to report).
set -uo pipefail

DOMAIN="${DOMAIN:-email.marvice.tech}"
DIR=/opt/BillionMail
DYN=/data/coolify/proxy/dynamic
fail() { echo; echo "RESULT: FAIL - $*"; exit 1; }

[ "$(id -u)" -eq 0 ] || fail "run as root"
[ -f "$DIR/.env" ] || fail "BillionMail not installed in $DIR (run vps-setup-billionmail.sh first)"
[ -d "$DYN" ] || fail "$DYN not found (is this Coolify's Traefik?)"
cd "$DIR" || fail "cannot cd to $DIR"
envval() { grep -E "^$1=" .env | tail -1 | cut -d= -f2-; }
HTTP_PORT=$(envval HTTP_PORT); SAFE=$(envval SafePath)
[ -n "$HTTP_PORT" ] || fail "HTTP_PORT missing from .env"

TC=$(docker ps --format '{{.Names}} {{.Image}}' | awk '/traefik/{print $1; exit}')
[ -n "$TC" ] || fail "no Traefik container running"
args=$(docker inspect -f '{{join .Args "\n"}}' "$TC")
EP_HTTPS=$(sed -nE 's/^--entry[pP]oints\.([^.]+)\.address=:443.*/\1/p' <<<"$args" | head -1); EP_HTTPS=${EP_HTTPS:-https}
EP_HTTP=$(sed -nE 's/^--entry[pP]oints\.([^.]+)\.address=:80$/\1/p' <<<"$args" | head -1); EP_HTTP=${EP_HTTP:-http}
RESOLVER=$(sed -nE 's/^--certificates[rR]esolvers\.([^.]+)\.acme\..*/\1/p' <<<"$args" | head -1); RESOLVER=${RESOLVER:-letsencrypt}
echo "==> Traefik ${TC}: entrypoints ${EP_HTTP}/${EP_HTTPS}, resolver ${RESOLVER}"

echo "==> Publishing the panel on the host (port ${HTTP_PORT}), dropping the label override"
[ -f docker-compose.override.yml ] && mv docker-compose.override.yml "docker-compose.override.yml.bak.$(date +%s)"
docker compose up -d --remove-orphans >/dev/null 2>&1 || docker compose up -d

echo "==> Waiting for the panel to answer on 127.0.0.1:${HTTP_PORT}"
code=000
for _ in $(seq 30); do
  code=$(curl -s -o /dev/null -m 5 -w '%{http_code}' "http://127.0.0.1:${HTTP_PORT}/" || true)
  [ "$code" != 000 ] && break
  sleep 5
done
if [ "$code" = 000 ]; then
  echo "---- core status/logs ----"
  docker compose ps --format '{{.Service}} {{.Status}}'
  docker compose logs --tail=15 core-billionmail
  fail "panel container not answering on port ${HTTP_PORT} (see logs above)"
fi
echo "    panel answers locally (HTTP ${code})"

# Traefik must be able to reach the host; Coolify's proxy maps host.docker.internal.
UPSTREAM="http://host.docker.internal:${HTTP_PORT}"
if ! docker exec "$TC" getent hosts host.docker.internal >/dev/null 2>&1; then
  gw=$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.Gateway}} {{end}}' "$TC" | awk '{print $1}')
  [ -n "$gw" ] || fail "can't find a host address reachable from Traefik"
  UPSTREAM="http://${gw}:${HTTP_PORT}"
fi
echo "==> Coolify dynamic route ${DOMAIN} -> ${UPSTREAM}"
cat > "$DYN/billionmail.yaml" <<EOF
# Generated by billionmail-repair.sh
http:
  middlewares:
    billionmail-https:
      redirectScheme:
        scheme: https
  routers:
    billionmail:
      rule: Host(\`${DOMAIN}\`)
      entryPoints: [${EP_HTTPS}]
      service: billionmail
      tls:
        certResolver: ${RESOLVER}
    billionmail-http:
      rule: Host(\`${DOMAIN}\`)
      entryPoints: [${EP_HTTP}]
      middlewares: [billionmail-https]
      service: billionmail
  services:
    billionmail:
      loadBalancer:
        servers:
          - url: ${UPSTREAM}
EOF

# Host firewall (ufw) may block docker-bridge -> host traffic on that port.
if ufw status 2>/dev/null | grep -q "Status: active"; then
  ufw allow from 172.16.0.0/12 to any port "$HTTP_PORT" proto tcp >/dev/null
  ufw allow from 10.0.0.0/8 to any port "$HTTP_PORT" proto tcp >/dev/null
fi

echo "==> Checking https://${DOMAIN} through Traefik"
code=000
for _ in $(seq 18); do
  code=$(curl -sk -o /dev/null -m 8 -w '%{http_code}' --resolve "${DOMAIN}:443:127.0.0.1" "https://${DOMAIN}/${SAFE}" || true)
  case "$code" in 000|404|502|503|504) sleep 5 ;; *) break ;; esac
done
case "$code" in
  000|502|503|504)
    echo "---- traefik ----"; docker logs --since 5m "$TC" 2>&1 | grep -iE 'billionmail|error' | tail -10
    fail "Traefik returns ${code} for ${DOMAIN}" ;;
esac

[ -x /usr/local/bin/billionmail-cert-sync ] && /usr/local/bin/billionmail-cert-sync >/dev/null 2>&1 || true
echo
echo "RESULT: PASS - open https://${DOMAIN}/${SAFE}  (login: cd ${DIR} && bash bm.sh default)"
